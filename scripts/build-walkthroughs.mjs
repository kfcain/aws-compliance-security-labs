#!/usr/bin/env node
/**
 * Writes the shared operator playbook and per-lab WALKTHROUGH.md files from
 * scripts/lab-operator-data.mjs. Deterministic so `--check` gates drift.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAB_OPS, SHARED_PARAMETERS, STACK_OUTPUTS } from './lab-operator-data.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const catalog = JSON.parse(readFileSync(join(root, 'labs/catalog.json'), 'utf8'));

function fence(lang, body) {
  return `\`\`\`${lang}\n${body.trim()}\n\`\`\`\n`;
}

function prettyJson(raw) {
  return JSON.stringify(JSON.parse(raw), null, 2);
}

function stackName(labId) {
  return `aws-lab-${labId.slice(0, 2)}`;
}

function invokeAndPackageScript(labId) {
  const stack = stackName(labId);
  return `STACK=${stack}
LAB=${labId}
OUT=/tmp/\${LAB}-out.json

# 1. Write the lab payload. Edit placeholders for your account.
cat > payload.json <<'JSON'
${prettyJson(LAB_OPS[labId].liveEvent.json)}
JSON

# 2. Resolve the worker ARN.
FUNC=$(aws cloudformation describe-stacks --stack-name "$STACK" \\
  --query "Stacks[0].Outputs[?OutputKey=='FunctionArn'].OutputValue" --output text)

# 3. Invoke. Transport statusCode is 200. Branch on compliance_status.
aws lambda invoke --function-name "$FUNC" --cli-binary-format raw-in-base64-out \\
  --payload file://payload.json "$OUT"
python3 -m json.tool "$OUT"

# 4. Copy the evidence object named in evidence_uri.
URI=$(python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); b=d["body"]; e=json.loads(b) if isinstance(b,str) else b; print(e["evidence_uri"])' "$OUT")
aws s3 cp "$URI" ./evidence.json
python3 -c 'import json; e=json.load(open("evidence.json")); print("status", e.get("status"), "data_source", e.get("data_source"), "uri", e.get("evidence_uri"))'

# 5. Assemble the assessor package for this run.
RUN=$(python3 -c 'import json,pathlib; e=json.load(open("evidence.json")); print(e.get("run_id") or pathlib.Path(e.get("evidence_uri","run")).stem)')
PKG="evidence-package/${labId}/$RUN"
mkdir -p "$PKG"
cp evidence.json payload.json "$PKG/"
cp "$OUT" "$PKG/invoke-response.json"
aws cloudformation describe-stacks --stack-name "$STACK" \\
  --query 'Stacks[0].Outputs' --output json > "$PKG/stack-outputs.json"
cp ASSESSMENT.md RISK.md SPEC.md "$PKG/" 2>/dev/null || true
cp scf/scf-mapping.generated.json scf/oscal-component.json "$PKG/" 2>/dev/null || true
echo "Assessor package: $PKG"
ls -la "$PKG"`;
}

function paramTable(rows) {
  let md = '| Parameter | Default | Meaning |\n|-----------|---------|---------|\n';
  for (const row of rows) md += `| \`${row.name}\` | ${row.default} | ${row.meaning} |\n`;
  return md;
}

function bullets(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

function numbered(items) {
  return items.map((item, i) => `${i + 1}. ${item}`).join('\n');
}

function playbookMarkdown() {
  return `# Operator playbook — configure, evidence, document

Generated by \`node scripts/build-walkthroughs.mjs\`. Do not edit by hand —
CI gates on drift. Lab-specific procedures live in each
\`labs/<id>/WALKTHROUGH.md\`.

Use a **sandbox account**. Do not point these stacks at production data,
production identity providers, or IAM principals you cannot suspend.

## 1. Configure (every lab)

### Tools

- AWS CLI v2, credentials for the sandbox account and region
- SAM CLI (\`sam build\` / \`sam deploy\`)
- Python 3.13 for offline tests
- Security Hub enabled in the region (FAIL imports ASFF findings)

### Offline check (no AWS)

From the repository root:

${fence('bash', `cd labs/<id>
python3 -c "import sys; sys.path.insert(0,'src'); import handler
class C:
    invoked_function_arn='arn:aws:lambda:us-east-1:123456789012:function:x'
    aws_request_id='local'
print(handler.handler({'mode':'simulation'}, C()))"`)}

Simulation is explicit: \`{"mode": "simulation"}\`. Simulated evidence is
stamped \`data_source: simulation\` and is not live posture.

### Deploy

${fence('bash', `cd labs/<id>
sam build -t infrastructure/template.yaml
sam deploy --guided --stack-name aws-lab-<nn> --capabilities CAPABILITY_IAM`)}

Shared parameters (all stacks):

${paramTable(SHARED_PARAMETERS)}

Destructive or account-singleton resources (GuardDuty detector, CloudTrail
trail, Config rules, purge, IAM suspend, Backup vault lock) default **off**.
Leave them off until the lab walkthrough says to enable them.

### Read outputs

${fence('bash', `aws cloudformation describe-stacks --stack-name aws-lab-<nn> \\
  --query 'Stacks[0].Outputs' --output table`)}

Every stack exports at least: ${STACK_OUTPUTS.map((o) => `\`${o}\``).join(', ')}.

### Fail-closed smoke test

For labs that need IdP, catalog, boundary, pipeline ARNs, or a plan, invoke
with those fields empty. The worker must return \`CONFIG_ERROR\`, never
\`PASS\`. Do not use an empty \`{}\` event on labs that treat that as a
scheduled sweep of live APIs (Config, GuardDuty, Inspector, KMS, VPC).
Transport \`statusCode\` is 200; branch on \`compliance_status\`.

## 2. Collect evidence

### Invoke the worker

${fence('bash', `FUNC=$(aws cloudformation describe-stacks --stack-name aws-lab-<nn> \\
  --query "Stacks[0].Outputs[?OutputKey=='FunctionArn'].OutputValue" --output text)
aws lambda invoke --function-name "$FUNC" --cli-binary-format raw-in-base64-out \\
  --payload '{"source":"manual"}' /tmp/lab-out.json
python3 -m json.tool /tmp/lab-out.json`)}

The daily EventBridge rule already sends \`{"source":"scheduled-sweep"}\`.
Use a lab-specific payload from that lab's \`WALKTHROUGH.md\` when the
control needs a case, inventory, plan, or descriptor.

### Where evidence lands

${fence('text', `s3://<EvidenceBucketName>/<lab-id>/<yyyy>/<mm>/<dd>/<run-id>.json
  SSE-KMS (lab CMK), versioned, TLS-only bucket policy
  optional Object Lock when EnableObjectLock=true
  lifecycle: STANDARD_IA at 90 days`)}

Prefer the \`evidence_uri\` field in the Lambda body. Fallback if you only
have the bucket name:

${fence('bash', `URI=$(python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); b=d["body"]; e=json.loads(b) if isinstance(b,str) else b; print(e["evidence_uri"])' /tmp/lab-out.json)
aws s3 cp "$URI" ./evidence.json

# Fallback: list the bucket
BUCKET=$(aws cloudformation describe-stacks --stack-name aws-lab-<nn> \\
  --query "Stacks[0].Outputs[?OutputKey=='EvidenceBucketName'].OutputValue" --output text)
aws s3 ls "s3://$BUCKET/<lab-id>/" --recursive
KEY=$(aws s3 ls "s3://$BUCKET/<lab-id>/" --recursive | awk '{print $4}' | tail -1)
aws s3 cp "s3://$BUCKET/$KEY" ./evidence.json
python3 -c 'import json; e=json.load(open("evidence.json")); print(e.get("status"), e.get("data_source"), e.get("evidence_uri"))'`)}

### Other evidence channels

| Channel | When |
|---------|------|
| Security Hub ASFF | \`FAIL\` (and some labs on other non-PASS outcomes) |
| SNS topic | Non-PASS. Confirm the email subscription or lab 09 FAIL on zero subscribers |
| CloudWatch Logs | \`/aws/lambda/<stack>-worker\`, JSON lines |
| SQS DLQ | Failed EventBridge deliveries |

### Verdicts

| \`compliance_status\` | Meaning |
|---------------------|---------|
| \`PASS\` | Live posture met the control. Not used for unconfigured runs. |
| \`FAIL\` | Control is operating and found a gap. Finding + SNS. |
| \`CONFIG_ERROR\` | Required config or sensor is missing. Never treat as PASS. |
| \`ERROR\` | Population could not be fully evaluated (malformed input). |
| \`NOT_APPLICABLE\` | Nothing in scope (for example zero VPCs, zero CMKs and secrets). |

## 3. Document (assessor package)

Create one folder per run, for example \`evidence/<lab-id>/<run-id>/\`:

| File | Source |
|------|--------|
| \`evidence.json\` | Object copied from the evidence bucket |
| \`invoke-response.json\` | Lambda payload (\`compliance_status\`) |
| \`stack-outputs.json\` | CloudFormation outputs |
| \`ASSESSMENT.md\` | Procedure table; record the run ID against each SCF row |
| \`scf-mapping.generated.json\` | Crosswalk in \`labs/<id>/scf/\` |
| \`oscal-component.json\` | OSCAL component in \`labs/<id>/scf/\` |
| \`RISK.md\` | Residual rating and ATT&CK |
| \`SPEC.md\` | Acceptance criteria |
| \`cloudwatch-snippet.json\` | Log lines for the run ID |
| \`screenshot-or-console.md\` | Security Hub finding ID if FAIL |

Each lab \`WALKTHROUGH.md\` writes \`evidence-package/<lab-id>/<run-id>/\`
with a copy-paste script. Stamp the package with account, region, stack
name, schedule, and \`data_source\` (\`aws-api\`, \`okta\`, \`descope\`,
\`event\`, or \`simulation\`). Simulation packages are demonstrations.
They are not authorization evidence.

## 4. Lab index

| Lab | Walkthrough |
|-----|-------------|
${catalog.labs.map((lab) => `| \`${lab.id}\` | [${lab.title}](../../${lab.path}/WALKTHROUGH.md) |`).join('\n')}
`;
}

function labMarkdown(lab) {
  const op = LAB_OPS[lab.id];
  const extras = (op.extraOutputs ?? []).map((o) => `\`${o}\``).join(', ');
  const outputLine = extras
    ? `Extra outputs: ${extras}.`
    : 'Uses the shared outputs only.';
  return `# Walkthrough — ${lab.title}

Generated by \`node scripts/build-walkthroughs.mjs\` from the SAM parameters
and handler contract. Do not edit by hand. Shared stack steps:
[docs/walkthroughs/00-operator-playbook.md](../../docs/walkthroughs/00-operator-playbook.md).

**Lab id:** \`${lab.id}\`  
**What the worker checks:** ${op.checks}

## 1. Configure

${bullets(op.prerequisites)}

${op.uniqueParameters.length ? `Lab-specific parameters:\n\n${paramTable(op.uniqueParameters)}\n` : 'This lab has no extra CloudFormation parameters beyond the shared set in the operator playbook.\n'}
${outputLine}

${numbered(op.configure)}

Example deploy (replace account-specific values):

${fence('bash', `cd labs/${lab.id}
sam build -t infrastructure/template.yaml
sam deploy --guided --stack-name ${stackName(lab.id)} --capabilities CAPABILITY_IAM`)}
${op.configureCli ? `\nLab-specific CLI (run in the sandbox account):\n\n${fence('bash', op.configureCli)}` : ''}
## 2. Collect evidence

**Live / scheduled event**

${op.liveEvent.label}

Copy the block below. It writes \`payload.json\`, invokes the worker, copies
the S3 evidence object from \`evidence_uri\`, and builds the assessor folder.

${fence('bash', invokeAndPackageScript(lab.id))}

Offline demonstration only (stamped \`data_source: simulation\`; not authorization evidence):

${fence('bash', `cd labs/${lab.id}
python3 -c "import sys; sys.path.insert(0,'src'); import handler
class C:
    invoked_function_arn='arn:aws:lambda:us-east-1:123456789012:function:x'
    aws_request_id='sim'
print(handler.handler({'mode':'simulation'}, C()))"`)}

Evidence object: \`s3://<EvidenceBucketName>/${lab.id}/<yyyy>/<mm>/<dd>/<run-id>.json\`
(SSE-KMS, versioned). The invoke body also contains \`compliance_status\` and
\`evidence_uri\`.

Read these fields in the JSON:

${bullets(op.evidenceLooksAt)}

## 3. Document

The script in section 2 writes \`evidence-package/${lab.id}/<run-id>/\`. Add
the lab-specific notes below, then record the evidence object key next to
each SCF row in [ASSESSMENT.md](./ASSESSMENT.md). Map residual risk in
[RISK.md](./RISK.md).

${bullets(op.documentNotes)}

Stamp the package with account, region, stack name, schedule, and
\`data_source\`. Simulation packages are demonstrations only.

## 4. Warnings

${bullets(op.warnings)}
`;
}

const missing = catalog.labs.filter((lab) => !LAB_OPS[lab.id]).map((lab) => lab.id);
const extra = Object.keys(LAB_OPS).filter((id) => !catalog.labs.some((lab) => lab.id === id));
if (missing.length || extra.length) {
  console.error(`lab-operator-data mismatch missing=${missing} extra=${extra}`);
  process.exit(1);
}

const targets = [[join(root, 'docs/walkthroughs/00-operator-playbook.md'), playbookMarkdown()]];
for (const lab of catalog.labs) {
  targets.push([join(root, lab.path, 'WALKTHROUGH.md'), labMarkdown(lab)]);
}

let drift = 0;
for (const [path, content] of targets) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`DRIFT: ${path} is stale`);
    drift += 1;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (check && drift) {
  console.error('\nRun: node scripts/build-walkthroughs.mjs');
  process.exit(1);
}
console.log(
  `walkthroughs ${check ? 'check OK' : 'built'} — ${catalog.labs.length} labs + playbook`,
);
