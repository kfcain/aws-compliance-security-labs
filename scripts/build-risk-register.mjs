#!/usr/bin/env node
/**
 * Rolls the per-lab RISK.md metadata tables up into a portfolio register at
 * RISKS.md. Deterministic — parses only committed files. `--check` gates
 * drift in CI.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const BAND_ORDER = { Severe: 0, Major: 1, Moderate: 2, Minor: 3 };
const L = { 'Very Low': 1, Low: 2, Medium: 3, High: 4, 'Very High': 5 };
const I = { 'Very Low': 1, Low: 2, Medium: 3, High: 4, Critical: 5 };

function band(likelihood, impact) {
  const l = L[likelihood] ?? 3;
  const i = I[impact] ?? 3;
  if (i === 5 && l >= 4) return 'Severe';
  if (l >= 4 && i >= 4) return 'Severe';
  if (i === 5 && l >= 3) return 'Major';
  if (l >= 4 && i === 3) return 'Major';
  if (l === 3 && i === 4) return 'Major';
  if (i === 5 && l <= 2) return 'Moderate';
  if (l >= 3 && i >= 3) return 'Moderate';
  if (l <= 2 && i >= 4) return 'Moderate';
  return 'Minor';
}

function field(text, name) {
  const re = new RegExp(`\\|\\s*${name.replace(/[/()]/g, '\\$&')}\\s*\\|\\s*(.+?)\\s*\\|`);
  const match = text.match(re);
  return match ? match[1].trim() : null;
}

function splitPair(value) {
  const [a, b] = (value ?? '').split('/').map((s) => s.trim());
  return [a, b];
}

const labDirs = readdirSync(join(root, 'labs'), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const rows = [];
for (const lab of labDirs) {
  const riskPath = join(root, 'labs', lab, 'RISK.md');
  if (!existsSync(riskPath)) continue;
  const text = readFileSync(riskPath, 'utf8');
  const [inL, inI] = splitPair(field(text, 'Inherent likelihood / impact'));
  const [resL, resI] = splitPair(field(text, 'Residual likelihood / impact'));
  const statement = (text.match(/## Statement\n\n\*\*(.+?)\*\*/s) ?? [])[1] ?? '';
  const techniques = [...text.matchAll(/\|\s*(T\d{4}(?:\.\d{3})?)\s*\|/g)].map((m) => m[1]);
  rows.push({
    risk_id: field(text, 'Risk ID'),
    lab,
    owner: field(text, 'Owner (role)'),
    statement,
    inherent: { likelihood: inL, impact: inI, band: band(inL, inI) },
    residual: { likelihood: resL, impact: resI, band: band(resL, resI) },
    treatment: field(text, 'Treatment decision'),
    reviewed: field(text, 'Reviewed'),
    next_review: field(text, 'Next review'),
    attack_techniques: [...new Set(techniques)],
  });
}

rows.sort(
  (a, b) =>
    BAND_ORDER[a.residual.band] - BAND_ORDER[b.residual.band] ||
    a.risk_id.localeCompare(b.risk_id),
);

let md = `# Portfolio Risk Register

Generated by \`node scripts/build-risk-register.mjs\` from each lab's
\`RISK.md\` metadata table. Do not edit by hand — CI gates on drift. Scales and
bands are defined in [docs/RISK-METHODOLOGY.md](docs/RISK-METHODOLOGY.md).
Rows are ordered by residual band (most severe first).

| Risk ID | Lab | Statement | Inherent | Residual | Owner | ATT&CK | Next review |
|---------|-----|-----------|----------|----------|-------|--------|-------------|
`;
for (const r of rows) {
  md += `| ${r.risk_id} | \`${r.lab}\` | ${r.statement} | ${r.inherent.likelihood}/${r.inherent.impact} (${r.inherent.band}) | ${r.residual.likelihood}/${r.residual.impact} (${r.residual.band}) | ${r.owner} | ${r.attack_techniques.join(', ')} | ${r.next_review} |\n`;
}

const bandCounts = rows.reduce((acc, r) => {
  acc[r.residual.band] = (acc[r.residual.band] ?? 0) + 1;
  return acc;
}, {});
md += `
## Residual band summary

| Band | Count |
|------|-------|
${['Severe', 'Major', 'Moderate', 'Minor'].map((b) => `| ${b} | ${bandCounts[b] ?? 0} |`).join('\n')}

All entries are treated **Mitigate** — automated by the corresponding lab's
continuous validation. Residual ratings assume each lab's controls are
deployed and kept healthy by CI; see each \`RISK.md\` for the delta rationale.
`;

const jsonOut =
  JSON.stringify({ risk_count: rows.length, band_summary: bandCounts, risks: rows }, null, 2) +
  '\n';

let drift = 0;
for (const [path, content] of [
  [join(root, 'RISKS.md'), md],
  [join(root, 'risks.json'), jsonOut],
]) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`DRIFT: ${path} is stale`);
    drift += 1;
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (check && drift) {
  console.error('\nRun: node scripts/build-risk-register.mjs');
  process.exit(1);
}
console.log(`risk register ${check ? 'check OK' : 'built'} — ${rows.length} risks`);
