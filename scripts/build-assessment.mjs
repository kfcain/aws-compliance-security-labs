#!/usr/bin/env node
/**
 * Generates a per-lab assessment procedure at labs/<id>/ASSESSMENT.md from the
 * post-processed SCF crosswalk. Each SCF control becomes a row of
 * objective -> test procedure -> expected evidence artifact, consuming the
 * SCF `evidence_requests` IDs the crosswalks carry but nothing else used.
 *
 * Deterministic (content-derived) so `--check` gates drift in CI. The test
 * procedure references the lab's own handler invocation and the
 * compliance_status field the handler emits, so an assessor can reproduce it.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const FRAMEWORK_LABELS = {
  'general-nist-800-53-r5-2': 'NIST 800-53 r5',
  'general-nist-800-171-r3': 'NIST 800-171 r3',
  'general-pci-dss-4-0-1': 'PCI DSS 4.0.1',
  'usa-federal-gsa-fedramp-5-mod': 'FedRAMP r5 Mod',
  'general-iso-27001-2022': 'ISO 27001:2022',
};

function frameworkCitations(control) {
  const parts = [];
  for (const [fw, label] of Object.entries(FRAMEWORK_LABELS)) {
    const hits = control.framework_mappings?.[fw];
    if (hits?.length) parts.push(`${label} ${hits.join(', ')}`);
  }
  return parts.join('; ') || '—';
}

function buildAssessment(labId, mapping) {
  const title = labId
    .replace(/^\d+-/, '')
    .split('-')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(' ');

  let md = `# Assessment Procedures — ${title}

Generated by \`node scripts/build-assessment.mjs\` from
\`scf/scf-mapping.generated.json\`. Do not edit by hand — CI gates on drift.

Each SCF control the lab claims is decomposed into an assessment objective, a
reproducible test procedure, and the expected evidence artifact. Procedures
invoke the lab's own handler; the pass/fail determination reads the
\`compliance_status\` field the handler emits (\`PASS\` / \`FAIL\` /
\`CONFIG_ERROR\` / \`NOT_APPLICABLE\`). Evidence-request IDs (e.g. \`E-MON-01\`)
are the SCF-defined artifacts and map to the JSON the handler persists to the
evidence bucket.

## How to run the check

\`\`\`bash
# Offline behavior demonstration (no AWS calls):
python3 -c "import json,sys; sys.path.insert(0,'labs/${labId}/src'); \\
  import handler; from tests_shim import ctx; \\
  print(handler.handler({'mode':'simulation'}, ctx()))"
# In-account: deploy infrastructure/template.yaml (sam deploy) and invoke the
# worker; inspect the evidence object written to the stack's evidence bucket.
\`\`\`

## Control assessment matrix

| SCF control | Objective | Test procedure | Expected evidence | Framework citations |
|-------------|-----------|----------------|-------------------|---------------------|
`;

  for (const control of mapping.controls) {
    const id = control.scf_control_id;
    const objective =
      `Confirm the ${control.family} objective "${control.title}" is operating: ` +
      `the handler evaluates live posture and returns a determination.`;
    const procedure =
      `Invoke the lab worker; verify \`compliance_status\` reflects real posture ` +
      `(unconfigured inputs must yield \`CONFIG_ERROR\`, never \`PASS\`).`;
    const evidenceIds = (control.evidence_requests ?? []).join(', ') || 'lab evidence JSON';
    const ksi = Object.keys(control.fedramp_20x_ksi ?? {});
    const objectiveCell = ksi.length ? `${objective} (KSI ${ksi.join(', ')})` : objective;
    md += `| ${id} | ${objectiveCell} | ${procedure} | ${evidenceIds} | ${frameworkCitations(control)} |\n`;
  }

  const pending = (mapping.coverage_summary?.frameworks_requested_without_hits ?? []).map(
    (e) => e.framework ?? e,
  );
  md += `
## Evidence handling

- **Where evidence lands:** \`s3://<stack-evidence-bucket>/${labId}/<yyyy>/<mm>/<dd>/<run-id>.json\`
  (SSE-KMS, versioned, optional Object Lock).
- **Retention:** the evidence bucket lifecycle transitions to STANDARD_IA at
  90 days; log retention is set by the \`LogRetentionDays\` stack parameter.
- **Determination source:** \`compliance_status\` in the handler response and
  the persisted evidence object; \`FAIL\` also raises a Security Hub ASFF
  finding and an SNS alert.
${
  pending.length
    ? `- **Framework coverage note:** ${pending
        .map((f) => FRAMEWORK_LABELS[f] ?? f)
        .join(', ')} currently have no SCF crosswalk hits for this lab's ` +
      'controls (tracked in [COVERAGE.md](../../COVERAGE.md); resolved by the ' +
      'scheduled scf-refresh regeneration).\n'
    : ''
}`;
  return md;
}

const labDirs = readdirSync(join(root, 'labs'), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

let drift = 0;
let written = 0;
for (const lab of labDirs) {
  const mappingPath = join(root, 'labs', lab, 'scf/scf-mapping.generated.json');
  if (!existsSync(mappingPath)) continue;
  const mapping = JSON.parse(readFileSync(mappingPath, 'utf8'));
  const outPath = join(root, 'labs', lab, 'ASSESSMENT.md');
  const output = buildAssessment(lab, mapping);
  written += 1;
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
  if (current === output) continue;
  if (check) {
    console.error(`DRIFT: ${outPath} is stale`);
    drift += 1;
  } else {
    writeFileSync(outPath, output);
    console.log(`wrote labs/${lab}/ASSESSMENT.md`);
  }
}
if (check && drift) {
  console.error('\nRun: node scripts/build-assessment.mjs');
  process.exit(1);
}
console.log(`assessment ${check ? 'check OK' : 'built'} — ${written} procedures`);
