#!/usr/bin/env node
/**
 * Portfolio control-coverage rollup: aggregates all 15
 * labs/<id>/scf/scf-mapping.generated.json files into COVERAGE.md and
 * coverage.json at the repo root.
 *
 * Deterministic (content-derived only — no wall-clock stamps) so `--check`
 * can gate drift in CI.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FEDRAMP_20X_KSI, KSI_OVERLAY_VERSION } from '../shared/scf-mapper/src/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const FRAMEWORK_LABELS = {
  'general-nist-800-53-r5-2': 'NIST 800-53 r5',
  'general-nist-800-171-r3': 'NIST 800-171 r3',
  'general-nist-800-171-r2': 'NIST 800-171 r2',
  'general-iso-27001-2022': 'ISO 27001:2022',
  'general-pci-dss-4-0-1': 'PCI DSS 4.0.1',
  'usa-federal-gsa-fedramp-5-mod': 'FedRAMP r5 Mod',
  'usa-federal-dow-cmmc-2-level-2': 'CMMC 2.0 L2',
};

const labDirs = readdirSync(join(root, 'labs'), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const labs = [];
for (const lab of labDirs) {
  const mappingPath = join(root, 'labs', lab, 'scf/scf-mapping.generated.json');
  if (!existsSync(mappingPath)) continue;
  const mapping = JSON.parse(readFileSync(mappingPath, 'utf8'));
  const requested = mapping.coverage_summary.frameworks_requested ?? [];
  const noHits = new Set(
    (mapping.coverage_summary.frameworks_requested_without_hits ?? []).map(
      (e) => e.framework ?? e,
    ),
  );
  const perFramework = {};
  const frameworkControls = {};
  for (const fw of requested) {
    const hits = mapping.controls.filter((c) => c.framework_mappings?.[fw]?.length);
    perFramework[fw] = hits.length;
    frameworkControls[fw] = [
      ...new Set(hits.flatMap((c) => c.framework_mappings[fw])),
    ].sort();
  }
  const ksiByControl = Object.fromEntries(
    mapping.controls.map((c) => [c.scf_control_id, Object.keys(c.fedramp_20x_ksi ?? {})]),
  );
  labs.push({
    lab_id: lab,
    scf_controls: mapping.controls.map((c) => c.scf_control_id),
    frameworks_requested: requested,
    mapped_control_counts: perFramework,
    framework_control_ids: frameworkControls,
    frameworks_without_hits: [...noHits].sort(),
    ksi_by_control: ksiByControl,
    generated_at: mapping.generated_at,
  });
}

// Portfolio rollups
const allFrameworks = [
  ...new Set(labs.flatMap((l) => l.frameworks_requested)),
].sort((a, b) => Object.keys(FRAMEWORK_LABELS).indexOf(a) - Object.keys(FRAMEWORK_LABELS).indexOf(b));
const portfolioFrameworkControls = {};
for (const fw of allFrameworks) {
  portfolioFrameworkControls[fw] = [
    ...new Set(labs.flatMap((l) => l.framework_control_ids[fw] ?? [])),
  ].sort();
}
const usedKsi = new Set(labs.flatMap((l) => Object.values(l.ksi_by_control).flat()));
const unusedKsi = Object.keys(FEDRAMP_20X_KSI).filter((k) => !usedKsi.has(k)).sort();
const scfControlLabs = {};
for (const lab of labs) {
  for (const control of lab.scf_controls) {
    (scfControlLabs[control] ??= []).push(lab.lab_id);
  }
}

const coverage = {
  ksi_overlay_version: KSI_OVERLAY_VERSION,
  lab_count: labs.length,
  frameworks: allFrameworks,
  labs,
  portfolio: {
    unique_scf_controls: Object.keys(scfControlLabs).sort(),
    scf_control_labs: Object.fromEntries(
      Object.entries(scfControlLabs).sort(([a], [b]) => a.localeCompare(b)),
    ),
    unique_framework_controls: Object.fromEntries(
      allFrameworks.map((fw) => [fw, portfolioFrameworkControls[fw].length]),
    ),
    framework_control_ids: portfolioFrameworkControls,
    ksi_in_use: [...usedKsi].sort(),
    ksi_defined_but_unused: unusedKsi,
  },
};

// ------------------------------- Markdown ---------------------------------
const short = (id) => id.split('-').slice(0, 1)[0];
let md = `# Portfolio Control Coverage

Generated by \`node scripts/build-coverage.mjs\` from the 15 per-lab SCF
crosswalks (\`labs/*/scf/scf-mapping.generated.json\`). Do not edit by hand —
CI gates on drift. KSI overlay: \`${KSI_OVERLAY_VERSION}\`.

Cells show **mapped SCF controls / declared SCF controls** for each lab and
framework. **0** means the declared controls have no crosswalk hits for that
framework in the current data (listed under each lab's
\`coverage_summary.frameworks_requested_without_hits\`; the scheduled
scf-refresh workflow confirms or backfills these — the CMMC / 800-171 r2
columns were added after the last live generation and are pending their
first pull).

| Lab | ${allFrameworks.map((f) => FRAMEWORK_LABELS[f] ?? f).join(' | ')} |
|-----|${allFrameworks.map(() => '----').join('|')}|
`;
for (const lab of labs) {
  const total = lab.scf_controls.length;
  const cells = allFrameworks.map((fw) => {
    if (!lab.frameworks_requested.includes(fw)) return '—';
    const count = lab.mapped_control_counts[fw] ?? 0;
    return count === 0 ? '**0**' : `${count}/${total}`;
  });
  md += `| \`${lab.lab_id}\` | ${cells.join(' | ')} |\n`;
}

md += `
## Portfolio rollup

| Framework | Unique framework controls covered |
|-----------|-----------------------------------|
`;
for (const fw of allFrameworks) {
  md += `| ${FRAMEWORK_LABELS[fw] ?? fw} | ${portfolioFrameworkControls[fw].length} |\n`;
}

md += `
## SCF control → labs

| SCF control | Labs |
|-------------|------|
`;
for (const [control, labIds] of Object.entries(coverage.portfolio.scf_control_labs)) {
  md += `| ${control} | ${labIds.map((l) => `\`${short(l)}\``).join(', ')} |\n`;
}

md += `
## FedRAMP 20x KSI usage

${coverage.portfolio.ksi_in_use.length} of ${Object.keys(FEDRAMP_20X_KSI).length} overlay KSIs are asserted by at least one control.

<details><summary>KSIs defined in the overlay but not asserted by any lab (${unusedKsi.length})</summary>

${unusedKsi.map((k) => `- \`${k}\` — ${FEDRAMP_20X_KSI[k]}`).join('\n')}

</details>
`;

const jsonOut = JSON.stringify(coverage, null, 2) + '\n';
const targets = [
  [join(root, 'coverage.json'), jsonOut],
  [join(root, 'COVERAGE.md'), md],
];
let drift = 0;
for (const [path, content] of targets) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`DRIFT: ${path} is stale`);
    drift += 1;
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (check && drift) {
  console.error('\nRun: node scripts/build-coverage.mjs');
  process.exit(1);
}
console.log(
  `coverage ${check ? 'check OK' : 'built'} — ${labs.length} labs, ` +
  `${coverage.portfolio.unique_scf_controls.length} unique SCF controls`,
);
